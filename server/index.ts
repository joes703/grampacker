import { Hono } from 'hono'
import { sql } from 'drizzle-orm'
import { createAuth } from './auth'
import { createDb } from './db'
import { assetCache, forceValidatedAssetResponse } from './middleware/asset-cache'
import { apiBodyLimit } from './middleware/body-limit'
import { csrfProtection } from './middleware/csrf'
import { errorHandler, withAuthErrorCorrelation } from './middleware/error-handler'
import { authRateLimit } from './middleware/rate-limit'
import { requireSession } from './middleware/session'
import { securityHeaders } from './middleware/security-headers'
import { categoryRoutes } from './routes/categories'
import { gearItemRoutes } from './routes/gear-items'
import { listRoutes } from './routes/lists'
import { packingLocationRoutes } from './routes/packing-locations'
import { meRoutes } from './routes/me'
import { shareRoutes } from './routes/shares'
import type { HealthResponse } from '../shared/health'
import { foodRoutes } from './routes/food'

// Env comes from worker-configuration.d.ts, generated by `wrangler types`
// from wrangler.jsonc (DB and ASSETS bindings).
//
// The root app owns the security-header map and the static-asset
// fallback; everything API-shaped lives on the /api sub-app. wrangler's
// run_worker_first: true routes ALL requests through the Worker, so no
// response - HTML shell, asset, or API - can skip the header map.
const app = new Hono<{ Bindings: Env }>()

app.use('*', securityHeaders)

// Long-lived browser caching for content-hashed assets only. Sits next to the
// header map rather than inside it: same "own every response" reason (
// run_worker_first routes even static files through here), different concern.
// It rebuilds the response itself, so it does not depend on running before or
// after securityHeaders.
app.use('*', assetCache)

const api = new Hono<{ Bindings: Env }>()

// Oversized bodies are refused (413) before any middleware or handler
// can consume them - including better-auth, which reads c.req.raw
// itself. Registered first on purpose: a 413 must not cost rate-limit
// budget or depend on auth state.
api.use('*', apiBodyLimit)

// Unsafe methods on our routes require the custom header + a matching
// Origin. Registered first so no later route can be added in front of it;
// it skips /api/auth/* internally (better-auth validates origins itself).
// Sub-app note: c.req.path stays the full /api/... path inside route(),
// so the middleware's path checks are unaffected by the mount.
api.use('*', csrfProtection)

// Abuse posture: /api/auth/* is rate limited per client IP before
// better-auth sees the request (its own limiter is explicitly disabled in
// authOptions - one mechanism, ours). Fail-closed across methods; see
// the allowlist in the middleware.
api.use('/auth/*', authRateLimit)

// Passkey freshness is gated INSIDE better-auth now, not here: a
// deny-by-default hooks.before in server/auth.ts covers every /passkey/*
// endpoint (with an explicit ungated allowlist), keyed on the RESOLVED
// endpoint path - so there is no second URL parser to diverge from the
// router, and a future plugin endpoint fails closed instead of shipping
// ungated. Account deletion is gated the same way by better-auth itself
// (session.freshAge via user.deleteUser, server/auth.ts).

// better-auth owns everything under /api/auth/* (magic-link send and verify,
// sign-out, passkeys). It does its own origin checking against baseURL. The
// email+password routes are still mounted by the library but answer 400 -
// there is no emailAndPassword config for them to run against.
//
// Wrapped for observability, not for behavior: better-call catches every throw
// inside its own router and RETURNS a Response, so nothing here ever reaches
// app.onError. Without this wrapper, auth 5xx would be the one part of the
// server outside the correlation scheme entirely.
api.on(['GET', 'POST'], '/auth/*', async (c) =>
  withAuthErrorCorrelation(await createAuth(c.env).handler(c.req.raw), {
    method: c.req.method,
    path: new URL(c.req.raw.url).pathname,
  }),
)

// ONE session gate for the three sub-apps that share the /lists base. Each
// used to gate itself with use('*', requireSession), and because a request
// falls through every sub-app on the mount until a route matches, a food
// request paid the better-auth session lookup (fresh instance + session +
// user reads) up to three times. Registration order is load-bearing TWICE:
// after csrfProtection above (403 without the header must precede 401
// without a session), and BEFORE the route() calls below - Hono copies
// sub-app routes into the parent at route() registration time, so a
// middleware registered after them would not wrap them at all.
// /me, /categories and /gear-items each still gate themselves.
api.use('/lists/*', requireSession)

api.route('/me', meRoutes)
api.route('/categories', categoryRoutes)
api.route('/gear-items', gearItemRoutes)
api.route('/lists', packingLocationRoutes)
api.route('/lists', listRoutes)
// Food lives under /lists/:id/food; mounted on the same base so the hoisted
// session gate above and the global CSRF layer cover it identically.
api.route('/lists', foodRoutes)
// Anonymous by design: the public share read (see routes/shares.ts for
// the trust model). Everything else API-shaped stays session-gated.
//
// Deliberately NOT metered in application code. Its budget is a Cloudflare
// rate limiting rule at the edge, which refuses before the Worker runs and
// before D1 is touched - an app-level counter would add a write to every
// anonymous view to protect a read. See SECURITY.md.
api.route('/shares', shareRoutes)

api.get('/health', async (c) => {
  // Round-trips through Drizzle to the D1 binding, so a green health check
  // proves the whole server stack, not just that Hono is routing.
  const db = createDb(c.env.DB)
  const row = await db.get<{ ok: number }>(sql`select 1 as ok`)
  const body: HealthResponse = { ok: row?.ok === 1 }
  return c.json(body)
})

// Unknown /api/* paths (including unregistered methods) stay JSON 404s
// instead of falling through to the SPA shell, which would answer 200
// with HTML and mask client-side typos.
api.all('*', (c) => c.json({ error: 'Not found' }, 404))

app.route('/api', api)

// Everything else is the SPA: the assets binding serves static files and
// falls back to index.html for client-side routes (single-page-application
// not_found_handling). ASSETS.fetch only serves GET/HEAD itself.
//
// Conditional headers are stripped from hashed-asset requests first, so the
// binding returns a 200 (which can carry the immutable policy) rather than a 304
// (which cannot). See forceValidatedAssetResponse - without it the caching win
// never reaches anyone who already has the app cached.
app.all('*', (c) => c.env.ASSETS.fetch(forceValidatedAssetResponse(c.req.raw)))

// Registered on the ROOT app, which catches throws from the /api sub-app too -
// a sub-app's own onError would win, so `api` deliberately has none. Everything
// this does and does not cover is documented in the middleware.
app.onError(errorHandler)

export default app
