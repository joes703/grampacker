-- Retire the last of the food PLANNER: every meal slot becomes usable again.
--
-- `needed` backed a "Nothing planned" warning and a Skip button that silenced
-- it. Neither ever reached the packing list or a weight, so both were removed
-- in the release before this one. What they left behind is rows still holding
-- 0 - two of them in production - and the 0017
-- `list_food_item_slots_needed_only` trigger, which refuses to associate food
-- with any slot whose `needed` is 0.
--
-- Without this those rows are HOSTILE rather than merely stale: the meal
-- renders as an ordinary empty row with a "+ Add", and adding food to it fails
-- with a 400 the user cannot act on and cannot undo, because the control that
-- set the flag no longer exists. The column is not droppable yet - that is a
-- contract step and it has to follow this one - so making every row usable is
-- what closes the gap.
--
-- ORDERING, STATED HONESTLY. This runs after the release that removed all
-- three writers (the PATCH route, setSlotNeeded, and the copy in list
-- duplication) has deployed. That is NOT a formal guarantee: deploy.yml
-- migrates before it swaps the Worker, so an in-flight request on the old
-- Worker could in principle write a 0 back afterwards, and a Cloudflare
-- rollback past that release would restore the writers against an
-- already-repaired database.
--
-- Both are left unguarded ON PURPOSE. This is a single-user app; each path
-- needs that one user to be mid-Skip during the seconds of a deploy, or to
-- roll the Worker back and then go looking for the button. The blast radius if
-- either somehow happened is one meal refusing food until this statement is
-- re-run. Database triggers rejecting non-1 writes would close both and were
-- written, tested and then removed: they bought nothing real here and would
-- have made the contract migration drop three triggers instead of one.
--
-- Data-only, so the destructive-DDL gate is not involved. The rewrite is
-- declared in EXPECTED_CHANGES in scripts/check-migration-safety.mjs, whose
-- fixture seeds a slot at 0 so the repair is asserted rather than assumed -
-- verified by gutting this statement and confirming the check fails.
--
-- `<> 1` rather than `= 0` because affinity lets a boolean column hold other
-- spellings; SQLite normalizes '1', '01' and 1.0 to integer 1, and anything
-- else compares unequal and is repaired here. NULL cannot occur - the column
-- is NOT NULL - so `IS NOT 1` would only buy tolerance for corruption the
-- schema already forbids.
--
-- The predicate keeps the write to rows that actually differ, which avoids
-- rewriting every slot for a no-op. It does NOT preserve `updated_at`, and an
-- earlier draft of this comment claimed it did: this statement never assigns
-- that column and no trigger maintains it, so slot timestamps are untouched
-- either way. Leaving them alone is deliberate - this is system repair, not
-- something the user did.
UPDATE `list_food_slots` SET `needed` = 1 WHERE `needed` <> 1;
