-- The contract half of four removals whose code shipped in earlier releases.
--
-- This is the first migration to remove anything since the destructive-DDL gate
-- was introduced. It is allowed because that gate now distinguishes two things
-- it previously treated as one:
--
--   A REBUILD is drizzle-kit's 12-step recipe for a constraint change -
--   CREATE __new_x; copy; DROP TABLE x; RENAME - and on D1 the
--   `PRAGMA foreign_keys=OFF` it wraps that in is a no-op, so the DROP TABLE
--   fires every child cascade. That is how migration 0009 wiped every
--   list_items row in production. Rebuilds remain banned, with no declaration.
--
--   A native ALTER TABLE ... DROP COLUMN is not that. It rewrites the table's
--   rows in place and never issues DROP TABLE, so no cascade fires - verified
--   against sqlite3 3.46.1 with foreign_keys=ON inside a transaction, which is
--   D1's exact setup. Every statement below was generated by drizzle-kit from
--   the schema, and it emitted plain ALTERs rather than a rebuild.
--
-- What made these wait is OUR deploy order, not SQLite: deploy.yml applies
-- migrations and THEN swaps the Worker, so a column dropped in the same release
-- that removed its reads 500s every request touching it until the deploy lands.
-- Each object below had its reads removed and DEPLOYED in an earlier release,
-- which is what CONTRACT_MIGRATIONS records.
--
-- ORDER IS LOAD-BEARING. The trigger goes first: SQLite refuses to drop a
-- column a trigger references, and fails the whole transaction if you try. The
-- reverse order does not corrupt anything - it just will not apply.
DROP TRIGGER `list_food_item_slots_needed_only`;--> statement-breakpoint
-- `needed` backed a "Nothing planned" warning and a Skip button that silenced
-- it. Neither ever reached the packing list or a weight. Removed in #213
-- (deployed), every row repaired to 1 by 0026 (deployed).
ALTER TABLE `list_food_slots` DROP COLUMN `needed`;--> statement-breakpoint
-- A per-list worn-grouping preference, dead since #110 made worn grouping
-- unconditional on 2026-07-21. Off every DTO and refused by the strict PATCH
-- schema ever since.
ALTER TABLE `lists` DROP COLUMN `group_worn`;--> statement-breakpoint
-- A per-list opt-in for the Ready column, likewise unconditional since
-- 2026-08-11. `is_ready` on each item was always independent of this flag, so
-- no tick was ever lost to it and none is lost now.
ALTER TABLE `lists` DROP COLUMN `ready_checks_enabled`;--> statement-breakpoint
-- 0023's one-shot rank repair mapping, emptied by that same migration. Nothing
-- references it - no foreign key points at it, so DROP TABLE here fires no
-- cascade. That is the only reason a DROP TABLE is permitted at all: a table
-- another table cascades FROM may never be dropped, declaration or not.
DROP TABLE `_food_rank_repair`;
